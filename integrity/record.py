def check_record(repo: Path, *, cfg: dict, mode: Optional[str] = None,
                 commit: Optional[str] = None, issue: Optional[int] = None,
                 attempt: Optional[int] = None, issue_text: str = "", result_text: str = "",
                 record_dir: Optional[Path] = None, write: bool = True,
                 config_path: Optional[Path] = None, version: str = "0"
                 ) -> tuple[int, dict, str]:
    """-> (exit code, record, stdout). Raises GitError / RefsError / ValueError on misconfig."""
    started = _now()
    mode = mode or cfg["mode"]
    if mode not in ("report", "enforce"):
        raise ValueError(f"mode must be report|enforce, not {mode!r}")
    if issue is None:
        m = re.match(r"^\s*#\s*#(\d+)", issue_text or "")
        issue = int(m.group(1)) if m else None
    if issue is None:
        raise ValueError("issue number unknown: pass --issue or set AGENT_ISSUE_NUMBER")
    repo = ensure_repo(Path(repo))
    exclude = []
    if record_dir is not None:
        try:
            exclude.append(Path(record_dir).resolve().relative_to(repo.resolve()).as_posix())
        except ValueError:
            pass
    cs = collect_changes(repo, commit, tuple(exclude))
    trees = Trees(repo, cs.old_rev, cs.new_rev)
    base = git_text(repo, "rev-parse", "--short", cs.old_rev).strip() \
        if cs.old_rev != EMPTY_TREE else "(none)"
    commit_sha = cs.new_rev
    compared = (f"{commit_sha[:10]}^..{commit_sha[:10]}" if commit_sha
                else f"HEAD..working tree (base {base})")
    findings: list[dict] = []
    changed = {c.path: c for c in cs.changes}
    trees.changed = set(changed)
    helper_cache: dict = {}

    # 1. locate the record
    rdir = norm_path(cfg["dir"]).rstrip("/")
    cands = [p for p in trees.list_dir(rdir)
             if (m := re.match(r"^(\d+)-.+\.md$", p.rsplit("/", 1)[-1], re.IGNORECASE))
             and int(m.group(1)) == issue]
    rec_path: Optional[str] = None
    want = f"{rdir}/{issue:04d}-<slug>.md"
    action: list[str] = []
    if not cands:
        findings.append(_finding(ERROR, "record_missing", f"no decision record for issue #{issue} "
                                 f"in {rdir}/", want))
        action.append(f"create {want} following the 'Decision record' format in the project "
                      "rules")
    elif len(cands) > 1:
        findings.append(_finding(ERROR, "record_ambiguous",
                                 f"{len(cands)} decision records for issue #{issue}: "
                                 + ", ".join(cands), ", ".join(cands)))
        action.append(f"keep exactly one record for issue #{issue} ({want}); merge or delete "
                      "the others")
    else:
        rec_path = cands[0]
        ch = changed.get(rec_path)
        old_t = _record_text(trees.read(rec_path, "old")) if ch and ch.change != "added" \
            else None
        new_t = _record_text(trees.read(rec_path, "new")) or ""
        if ch is None or (old_t is not None and rationale_of(old_t) == rationale_of(new_t)):
            findings.append(_finding(ERROR, "record_not_updated",
                                     f"decision record not updated by this change: {rec_path}",
                                     rec_path))
            action.append(f"update {rec_path} so it describes this change (a retry updates the "
                          "same file)")

    parsed = Parsed()
    sections = {"present": [], "missing": [], "waived": []}
    coverage = {"changed_components": 0, "mentioned": 0, "unmentioned": []}
    oos_info = {"total": 0, "explained": 0, "items": []}
    removed_info = {"total": 0, "mentioned": 0, "items": []}
    rows: list[dict] = []
    claims: list[dict] = []
    misc = {"tests": 0, "docs": 0}
    scope_declared = None
    scope_verdict = "no Scope line"
    text = ""
    usable = rec_path is not None and not any(f["code"] == "record_not_updated" for f in findings)
    if rec_path is not None:
        text = expand_braces(rationale_of(_record_text(trees.read(rec_path, "new")) or ""))
        text = expand_ellipsis(text, trees, list(changed))
        parsed = parse_markdown(text)

    # changed components (classification with an empty scope)
    scfg = scope_load_config(config_path)
    files = classify(cs, Scope([]), scfg)
    rec_dirs = [rdir + "/"]
    comps = []
    for fr in files:
        for f in fr.findings:
            if f.component == IMPORTS:
                continue
            cls = refs.hit_class(fr.path)
            is_record = fr.path == rec_path
            testdoc = (cls in ("test", "doc") or f.reason == "allow_glob"
                       or fr.path.startswith(tuple(rec_dirs)))
            if testdoc or is_record:
                if not is_record:
                    misc["tests" if cls == "test" else "docs"] += 1
                continue
            chg = {"added": "new file", "removed": "deleted file", "renamed": "renamed"}.get(
                fr.change, "modified") if f.component == FILE else f.change
            row = {"path": fr.path, "component": f.component, "old_path": fr.old_path,
                   "label": _label(fr.path, f.component), "change": chg,
                   "added": f.lines_added, "removed": f.lines_removed, "tags": list(f.tags),
                   "description": f.description, "whitespace_only": f.whitespace_only,
                   "unparsed": f.category == "unverified"}
            rows.append(row)
            if f.component == FILE and fr.change == "added":     # list a new file's parts
                data = trees.read(fr.path, "new")
                pp = adapter_for(fr.path).parse(data or b"", fr.path)
                if not pp.error and not pp.whole_file:
                    for c in pp.components:
                        if c.parent is None or c.kind in ("method", "async_method"):
                            rows.append({"path": fr.path, "component": c.qualname,
                                         "old_path": None,
                                         "label": _label(fr.path, c.qualname), "change": "added",
                                         "added": c.span[1] - c.span[0] + 1, "removed": 0,
                                         "tags": list(c.tags), "description": c.description,
                                         "whitespace_only": False, "unparsed": False,
                                         "in_new_file": True})
            comps.append(row)

    if usable:
        # 2a. sections (v1 records are checked against the v1 list)
        rec_version = record_version(parsed)
        if rec_version == 1:
            findings.append(_finding(INFO, "record_v1", "v1 record (Approach format); checked "
                                     "against the v1 section list", "v1"))
        for name in required_for(cfg, rec_version):
            sec = find_section(parsed, name)
            if sec is None:
                sections["missing"].append(name)
                continue
            sections["present"].append(name)
            if is_waiver(sec[1]):
                sections["waived"].append(name)
        if BREAKS in sections["missing"] and (parsed.date or "9999") < BREAKS_DATE:
            sections["missing"].remove(BREAKS)
            findings.append(_finding(WARN, "section_missing", f"missing section: {BREAKS} "
                                     f"(required for records dated {BREAKS_DATE} or later)",
                                     BREAKS))
        if (parsed.date or "9999") < HUMAN_DATE:      # older records: not required, no error
            for name in HUMAN_SECTIONS:
                if name in sections["missing"]:
                    sections["missing"].remove(name)
        findings.extend(human_layer_warns(parsed))
        if sections["missing"]:
            findings.append(_finding(ERROR, "section_missing", "missing section(s): "
                                     + ", ".join(sections["missing"]),
                                     ", ".join(sections["missing"])))
            action.append(f"add the missing section(s) to {rec_path}: "
                          + ", ".join(f"## {s}" for s in sections["missing"])
                          + " (write 'None' or 'Not applicable' if there is nothing to say)")
        for name in sections["waived"]:
            findings.append(_finding(INFO, "section_waived", f"section '{name}' is waived "
                                     "(None / N/A / Not checked)", name))
        # 2b. status
        if parsed.status is None:
            findings.append(_finding(ERROR, "status_invalid",
                                     "Status line missing" if parsed.status_raw is None else
                                     f"Status must be one of implemented|partial|blocked: "
                                     f"{parsed.status_raw!r}", parsed.status_raw or ""))
            action.append(f"put one line under the title of {rec_path}: 'Status: implemented' "
                          "(or partial / blocked) · Issue: #N · Date: YYYY-MM-DD")
        # 2c. length
        max_w = cfg["max_words"] if rec_version == 2 else max(cfg["max_words"], V1_MAX_WORDS)
        if not (cfg["min_words"] <= parsed.words <= max_w):
            findings.append(_finding(WARN, "word_count",
                                     f"record has {parsed.words} words (expected "
                                     f"{cfg['min_words']}-{max_w})", str(parsed.words)))
        # 2d. status vs agent result
        rs = _result_status(result_text)
        if rs and parsed.status:
            if (rs == "COMPLETE") != (parsed.status == "implemented"):
                findings.append(_finding(WARN, "status_mismatch",
                                         f"record says Status: {parsed.status} but the agent "
                                         f"result says STATUS: {rs}", rs))
        # 2e. verification claims
        flagged: set[str] = set()
        ver = find_section(parsed, "How it was verified")
        if ver:
            body = ver[1]
            for pth in path_refs(body) + [p for p, _ in comp_refs(body)]:
                if refs.hit_class(pth) == "test" and pth not in flagged \
                        and trees.resolve(pth)[0] == "missing":
                    flagged.add(pth)
                    findings.append(_finding(WARN, "verify_missing", "'How it was verified' names "
                                             f"a test file that does not exist: {pth}", pth))
            for name in dict.fromkeys(TEST_NAME_RE.findall(body)):
                if not _test_name_exists(repo, cs.new_rev, name):
                    flagged.add(name)
                    findings.append(_finding(WARN, "verify_missing", "'How it was verified' names "
                                             f"a test that does not exist: {name}", name))
        # 2f. references to code that does not exist
        crefs = comp_refs(text)
        for pth, q in crefs:
            lab = f"{pth}::{q}"
            if pth in flagged or lab in flagged:
                continue
            st, ps = trees.resolve(pth, q)
            if st == "missing":
                flagged.add(pth)
                findings.append(_finding(WARN, "ref_missing", "references something that doesn't "
                                         f"exist: {lab} (no such file)", lab))
                continue
            if st == "ambiguous" and disambiguate(ps, pth, text):
                continue
            if st == "ambiguous":
                flagged.add(lab)
                findings.append(_finding(WARN, "ref_ambiguous", f"ambiguous reference: {lab} "
                                         f"matches {len(ps)} files ({', '.join(ps[:4])}) and none "
                                         "defines it; use the repo-relative path", lab))
                continue
            if not any(trees.has_comp(x, q) for x in ps):
                flagged.add(lab)
                findings.append(_finding(WARN, "ref_missing", "references something that doesn't "
                                         f"exist: {lab} (no such component in the old or new "
                                         "version)", lab))
        for pth in path_refs(text):
            if pth in flagged or pth.rstrip("/") in flagged:
                continue
            st, ps = trees.resolve(pth)
            if st == "ambiguous" and disambiguate(ps, pth, text):
                continue
            if st == "missing" and url_like(pth, trees):
                continue
            if st == "missing" and git_ignored(repo, pth):
                flagged.add(pth)
                findings.append(_finding(INFO, "ref_ignored", f"names a git-ignored path that "
                                         f"is not in the repo: {pth}", pth))
                continue
            if st == "missing":
                flagged.add(pth)
                findings.append(_finding(WARN, "ref_missing", "references something that doesn't "
                                         f"exist: {pth}", pth))
            elif st == "ambiguous" and not set(ps) & set(changed):
                flagged.add(pth)
                findings.append(_finding(WARN, "ref_ambiguous", f"ambiguous reference: {pth} "
                                         f"matches {len(ps)} files ({', '.join(ps[:4])}); use "
                                         "the repo-relative path", pth))
        # 2g. coverage
        rrefs = resolve_refs(crefs, trees)
        dirs_named = mentioned_dirs(text, trees)
        for row in comps:
            if row["whitespace_only"]:
                continue
            if row["component"] != FILE and (row["added"] + row["removed"] <= MINOR_LINES
                                             or is_private(row["path"], row["component"], trees)):
                coverage["skipped_minor"] = coverage.get("skipped_minor", 0) + 1
                continue
            coverage["changed_components"] += 1
            if under_dirs(row["path"], dirs_named) or under_dirs(row["old_path"], dirs_named):
                ok = True
            elif row.get("component") == FILE and row["change"] == "new file":
                # any mention of a new file (any unique spelling), incl. path::Name
                ok = any(re.search(r"(?<![\w/.\-])" + re.escape(a) + r"(?![\w\-])", text)
                         for a in trees.aliases(row["path"]))
            else:
                ok = comp_mentioned(text, rrefs, row["path"], row["component"], row["old_path"],
                                    removed=row["change"] == "removed", trees=trees)
            if not ok and row["component"] not in PSEUDO and any(
                    p in (row["path"], row["old_path"]) and mq != row["component"]
                    for p, mq in rrefs) and same_file_helper(row["path"], row["component"],
                                                             trees, repo, cs.new_rev,
                                                             helper_cache):
                coverage["same_file_helper"] = coverage.get("same_file_helper", 0) + 1
                coverage["changed_components"] -= 1
                continue
            if ok:
                coverage["mentioned"] += 1
            else:
                coverage["unmentioned"].append(row["label"])
                findings.append(_finding(WARN, "unmentioned_change", f"{row['label']} "
                                         f"({row['change']}) changed but not mentioned in the "
                                         "record", row["label"]))
        # 2g'. numeric claims citing a constant
        for c in numeric_claims(text, trees):
            claims.append(c)
            nums = ", ".join(_fmt(n) for n in c["numbers"])
            if c["contradiction"]:
                findings.append(_finding(WARN, "claim_mismatch", f"record states {nums} next to "
                                         f"`{c['ref']}`, but {c['name']} = {_fmt(c['value'])}",
                                         c["ref"]))
            else:
                findings.append(_finding(INFO, "claim_cites", f"claim cites {c['name']} = "
                                         f"{_fmt(c['value'])} (record says {nums})", c["ref"]))
    # 2h. out of scope
    scope = parse_scope(issue_text or "")
    if scope is not None:
        scope_declared = scope.as_list()
        sfiles = classify(cs, scope, scfg, parse_scope_notes(result_text))
        oos = [f for fr in sfiles for f in fr.findings if f.category == OUT_OF_SCOPE]
        scope_verdict = "violation" if oos else "pass"
        sec = find_section(parsed, "Changes outside the scope") if usable else None
        stext = sec[1] if sec else ""
        srefs = resolve_refs(comp_refs(stext), trees)
        olds = {fr.path: fr.old_path for fr in sfiles}
        arefs = resolve_refs(comp_refs(text), trees) if usable else []
        for f in oos:
            lab = f.target
            ok = comp_mentioned(stext, srefs, f.path, f.component, olds.get(f.path),
                                removed=f.change == "removed", trees=trees) if usable else False
            how = "record" if ok else ""
            if usable and not ok and f.component in (MODULE, IMPORTS):
                # module-level code / imports of a file the record names anywhere
                ok = any(p in (f.path, olds.get(f.path)) for p, _ in arefs) or any(
                    path_mentioned(text, a) for a in trees.aliases(f.path))
                how = "file_mentioned" if ok else ""
            if usable and not ok and f.change != "removed" and scope.has_components(f.path) \
                    and same_file_helper(f.path, f.component, trees, repo, cs.new_rev,
                                         helper_cache):
                ok, how = True, "same_file_helper"
            oos_info["total"] += 1
            oos_info["explained"] += int(ok)
            oos_info["items"].append({"target": lab, "explained": ok, "change": f.change,
                                      "how": how})
            if usable and not ok:
                findings.append(_finding(WARN, "oos_unexplained", f"out-of-scope change not "
                                         f"explained in 'Changes outside the scope': {lab}", lab))
    # 2i. removed symbols
    rcfg = refs.load_config(config_path)
    rem = removed_symbols(cs, trees)
    dang, _ = refs.find_dangling(repo, commit, rcfg, tuple(exclude))
    sev = {(r.path, r.sym.display): r for r in dang}
    for r in rem:
        d = sev.get((r["path"], r["symbol"]))
        r["refs"] = d.severity if d else "unreferenced"
        r["code_hits"] = sum(1 for h in d.hits if h["class"] in ("code", "test")) if d else 0
        r["mentioned"] = bool(usable and (re.search(r"(?<![\w$])" + re.escape(r["name"])
                                                    + r"(?![\w$])", text)))
        removed_info["total"] += 1
        removed_info["mentioned"] += int(r["mentioned"])
        removed_info["items"].append(r)
        if usable and not r["mentioned"] and r["refs"] == "dangling":
            findings.append(_finding(WARN, "removed_unmentioned", f"removed {r['kind']} "
                                     f"{r['symbol']} (from {r['path']}) without mentioning it",
                                     f"{r['path']}::{r['symbol']}"))

    # 2j. evidence levels (the tool's, never the agent's) and breaks
    gates = _gates_passed()
    ev = {"sections": {}, "totals": {"checked": 0, "tested": 0, "claimed": 0}, "items": [],
          "test_gate": None}
    breaks: list[str] = []
    if usable:
        ev = evidence(parsed, EvidenceCtx(repo, trees, comps, cs.new_rev, gates,
                                          cfg.get("test_gate_re") or DEFAULT_TEST_GATE_RE))
        selfd = SELF_LEVEL_RE.findall(text)
        if selfd:
            lv = ", ".join(sorted({"[" + x.lower() + "]" for x in selfd}))
            findings.append(_finding(WARN, "self_declared_evidence", f"the record marks its own "
                                     f"claims {lv}; evidence levels are set by the tool only "
                                     "(ignored)", str(len(selfd))))
        breaks = section_items(parsed, BREAKS)
    seen_msgs: set = set()                        # the same message once
    findings = [f for f in findings
                if not (f["message"] in seen_msgs or seen_msgs.add(f["message"]))]
    counts = {s: sum(1 for f in findings if f["severity"] == s) for s in (ERROR, WARN, INFO)}
    verdict = "fail" if counts[ERROR] else "pass"

    # 3. facts block
    facts = render_facts(issue=issue, attempt=attempt, compared=compared, rows=rows, misc=misc,
                         removed=removed_info["items"], scope_declared=scope_declared,
                         scope_verdict=scope_verdict, oos=oos_info["items"], gates=gates,
                         counts=counts, findings=findings, rec_path=rec_path or want,
                         commit_mode=commit is not None, evidence=ev)
    facts_written = False
    if write and commit is None and usable:
        f = repo / rec_path
        data = f.read_bytes()
        new = with_banner(with_facts(data, facts))
        if new != data:
            f.write_bytes(new)
        facts_written = True

    rec = {"schema_version": SCHEMA_VERSION, "tool": "integrity record", "tool_version": version,
           "issue": issue, "attempt": attempt, "commit": commit_sha, "compared": compared,
           "mode": mode, "verdict": verdict, "record_path": rec_path,
           "word_count": parsed.words if rec_path else 0,
           "status": parsed.status, "result_status": _result_status(result_text),
           "sections": sections, "findings": findings, "counts": counts,
           "coverage": coverage,
           "out_of_scope": {"total": oos_info["total"], "explained": oos_info["explained"],
                            "items": oos_info["items"]},
           "removed_symbols": {"total": removed_info["total"],
                               "mentioned": removed_info["mentioned"],
                               "items": removed_info["items"]},
           "scope_declared": scope_declared, "gates_passed": gates,
           "record_version": record_version(parsed) if rec_path else None,
           "claims": claims, "evidence": ev, "breaks": breaks,
           "facts_written": facts_written, "started": started, "finished": _now()}
    out = render_stdout(rec, action)
    if commit is not None:
        out += "\n\n" + "\n".join([BANNER_BEGIN, BANNER_TEXT, BANNER_END, "", BEGIN] + facts
                                    + [END])
    elif facts_written:
        out += f"\n(verified facts written to {rec_path})"
    if record_dir is not None:
        record_dir = Path(record_dir)
        record_dir.mkdir(parents=True, exist_ok=True)
        stem = (f"record_issue-{issue}_attempt-{attempt if attempt is not None else 0}"
                if commit is None else f"record_commit-{commit_sha[:10]}")
        (record_dir / f"{stem}.json").write_text(json.dumps(rec, indent=2), encoding="utf-8")
        out += f"\n(record: {record_dir / (stem + '.json')})"
    rc = FAIL if verdict == "fail" and mode == "enforce" else PASS
    return rc, rec, out


