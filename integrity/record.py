def _cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def render_facts(*, issue, attempt, compared, rows, misc, removed, scope_declared,
                 scope_verdict, oos, gates, counts, findings, rec_path, commit_mode) -> list[str]:
    ts = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    att = f" attempt {attempt}" if attempt is not None else ""
    L = ["## Verified facts", "",
         f"Generated {ts} for issue #{issue}{att}; compared {compared}.", "",
         "**Changed components**", ""]
    if rows:
        L += ["| Component | Change | Lines +/- | Tags | Description |", "|---|---|---|---|---|"]
        for r in rows:
            chg = r["change"] + (" (whitespace only)" if r["whitespace_only"] else "") + \
                (" (could not parse)" if r["unparsed"] else "") + \
                (f" (from {r['old_path']})" if r.get("old_path") and r["change"] == "renamed"
                 else "")
            L.append(f"| `{_cell(r['label'])}` | {chg} | +{r['added']}/-{r['removed']} | "
                     f"{_cell(', '.join(r['tags']))} | {_cell(r['description'])} |")
    else:
        L.append("No code components changed.")
    extra = [f"{misc['tests']} test file(s)" if misc["tests"] else "",
             f"{misc['docs']} doc file(s)" if misc["docs"] else ""]
    extra = [x for x in extra if x]
    if extra:
        L += ["", "Plus " + ", ".join(extra) + "."]
    L += ["", "**Removed symbols**", ""]
    if removed:
        verdict = {"dangling": "STILL REFERENCED in code", "doc_only": "referenced in docs only",
                   "unreferenced": "no remaining references"}
        for r in removed:
            L.append(f"- `{r['path']}::{r['symbol']}` ({r['kind']}): "
                     f"{verdict.get(r['refs'], r['refs'])}")
    else:
        L.append("None.")
    L += ["", "**Scope**", ""]
    if scope_declared is None:
        L.append("No Scope line in the issue.")
    else:
        L.append("Declared: " + (", ".join(f"`{s}`" for s in scope_declared) or "(empty)")
                 + f". Verdict: {scope_verdict}.")
        for o in oos:
            L.append(f"- out of scope: `{o['target']}` ({o['change']}); explained in the record: "
                     f"{'yes' if o['explained'] else 'no'}")
    L += ["", "**Supervisor checks passed**", ""]
    L.append(", ".join(gates) if gates else ("none" if gates == [] else "not available"))
    L += ["", "**Consistency**", ""]
    L.append(f"{counts[ERROR]} error(s), {counts[WARN]} warning(s) between the rationale above "
             "and the change.")
    for f in findings:
        if f["severity"] in (ERROR, WARN):
            L.append(f"- {f['severity']}: {f['message']}")
    L += ["", "**Commit**", ""]
    L.append("This record is committed with the change it describes; "
             f"`git log -1 -- {rec_path}` gives the commit.")
    return L


def render_stdout(rec: dict, action: list[str]) -> str:
    c = rec["counts"]
    head = (f"DECISION RECORD: {rec['verdict'].upper()} ({rec['mode']} mode) - "
            f"{rec['record_path'] or 'no record'}: {c[ERROR]} error(s), {c[WARN]} warning(s), "
            f"{c[INFO]} info  [{rec['compared']}]")
    out = [head]
    errs = [f for f in rec["findings"] if f["severity"] == ERROR]
    warns = [f for f in rec["findings"] if f["severity"] == WARN]
    if errs:
        out.append("ERRORS (must fix):")
        out += [f"  - {f['message']}" for f in errs]
        out.append("ACTION: " + "; ".join(action) + ".")
    if warns:
        out.append("WARNINGS (not blocking; fix the record if it is wrong):")
        out += [f"  - {f['message']}" for f in warns[:30]]
        if len(warns) > 30:
            out.append(f"  ... {len(warns) - 30} more in the record")
    cov = rec["coverage"]
    out.append(f"coverage: {cov['mentioned']}/{cov['changed_components']} changed component(s) "
               f"mentioned; out-of-scope explained {rec['out_of_scope']['explained']}/"
               f"{rec['out_of_scope']['total']}; removed symbols mentioned "
               f"{rec['removed_symbols']['mentioned']}/{rec['removed_symbols']['total']}")
    return "\n".join(out)


