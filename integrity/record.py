def _cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def _area(path: str) -> str:
    parts = path.split("/")
    return "/".join(parts[:2]) if len(parts) > 2 else (parts[0] if len(parts) > 1 else "(root)")


def render_facts(*, issue, attempt, compared, rows, misc, removed, scope_declared,
                 scope_verdict, oos, gates, counts, findings, rec_path, commit_mode,
                 evidence=None) -> list[str]:
    """Compact facts: change summary by area, new files, removed symbols, checks passed and
    at most MAX_FACT_WARNS warnings (the full list is in the JSON record)."""
    ts = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    att = f" attempt {attempt}" if attempt is not None else ""
    L = ["## Verified facts", "",
         f"Generated {ts} for issue #{issue}{att}; compared {compared}. "
         "Records are claims to check against the code, not proof.", "",
         "**Change summary**", ""]
    real = [r for r in rows if not r.get("in_new_file")]
    if real:
        areas: dict = {}
        for r in real:
            a = areas.setdefault(_area(r["path"]), {"files": set(), "comps": 0, "add": 0,
                                                    "rem": 0})
            a["files"].add(r["path"])
            a["comps"] += int(r["component"] != FILE)
            a["add"] += r["added"]
            a["rem"] += r["removed"]
        for name, a in sorted(areas.items()):
            L.append(f"- `{name}/`: {len(a['files'])} file(s), {a['comps']} component(s), "
                     f"+{a['add']}/-{a['rem']} lines")
    else:
        L.append("No code components changed.")
    extra = [f"{misc['tests']} test file(s)" if misc["tests"] else "",
             f"{misc['docs']} doc file(s)" if misc["docs"] else ""]
    extra = [x for x in extra if x]
    if extra:
        L.append("- plus " + ", ".join(extra))
    new_files = [r["path"] for r in real if r["change"] == "new file"]
    gone = [r["path"] for r in real if r["change"] == "deleted file"]
    if new_files:
        L.append("- new files: " + ", ".join(f"`{x}`" for x in new_files))
    if gone:
        L.append("- deleted files: " + ", ".join(f"`{x}`" for x in gone))
    L += ["", "**Removed symbols**", ""]
    if removed:
        verdict = {"dangling": "STILL REFERENCED in code", "doc_only": "referenced in docs only",
                   "unreferenced": "no remaining references"}
        by: dict = {}
        for r in removed:
            by.setdefault(r["refs"], []).append(f"`{r['path']}::{r['symbol']}`")
        for k, v in by.items():
            shown = ", ".join(v[:8]) + (f" (+{len(v) - 8} more)" if len(v) > 8 else "")
            L.append(f"- {verdict.get(k, k)}: {shown}")
    else:
        L.append("None.")
    L += ["", "**Scope**", ""]
    if scope_declared is None:
        L.append("No Scope line in the issue.")
    else:
        L.append("Declared: " + (", ".join(f"`{s}`" for s in scope_declared) or "(empty)")
                 + f". Verdict: {scope_verdict}.")
        for o in oos:
            L.append(f"- out of scope: `{o['target']}` ({o['change']}); explained in the record: "
                     f"{'yes' if o['explained'] else 'no'}")
    L += ["", "**Supervisor checks passed**", ""]
    L.append(", ".join(gates) if gates else ("none" if gates == [] else "not available"))
    if evidence and evidence.get("items"):
        t = evidence["totals"]
        n = sum(t.values())
