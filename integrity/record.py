# ---------------------------------------------------------------------------

def split_facts(text: str) -> tuple[str, Optional[str], str]:
    """-> (before, block incl. markers and its line ending, after). block None if absent."""
    b = text.find(BEGIN)
    if b < 0:
        return text, None, ""
    ls = text.rfind("\n", 0, b) + 1               # start of the marker's line
    e = text.find(END, b)
    if e < 0:                                     # unterminated: treat the rest as the block
        return text[:ls], text[ls:], ""
    end = e + len(END)
    if text.startswith("\r\n", end):
        end += 2
    elif text.startswith("\n", end):
        end += 1
    return text[:ls], text[ls:end], text[end:]


def strip_banner(text: str) -> str:
    """Remove the tool's verify banner (its marker lines and the lines between)."""
    b = text.find(BANNER_BEGIN)
    if b < 0:
        return text
    ls = text.rfind("\n", 0, b) + 1
    e = text.find(BANNER_END, b)
    if e < 0:
        return text
    end = e + len(BANNER_END)
    if text.startswith("\r\n", end):
        end += 2
    elif text.startswith("\n", end):
        end += 1
    return text[:ls] + text[end:]


def rationale_of(text: str) -> str:
    before, _, after = split_facts(text)
    return strip_banner(before + after).replace("\r\n", "\n")


def with_banner(data: bytes) -> bytes:
    """Write (or replace) the verify banner right under the title line. Idempotent; the
    record's encoding, BOM and newline style are kept (a code page that cannot encode the
    warning sign gets 'WARNING:' instead)."""
    bom = data.startswith(b"\xef\xbb\xbf")
    text, enc = _decode_record(data[3:] if bom else data)
    nl = "\r\n" if "\r\n" in text else "\n"
    text = strip_banner(text)
    line = BANNER_TEXT
    try:
        line.encode(enc)
    except UnicodeEncodeError:
        line = line.replace("⚠", "WARNING:").replace("·", "|")
    block = nl.join([BANNER_BEGIN, line, BANNER_END]) + nl
    m = re.search(r"^#\s+\S[^\n]*(?:\n|$)", text, re.M)
    if m:
        at = m.end()
        head = text[:at] if text[:at].endswith("\n") else text[:at] + nl
        out = head + block + text[at:]
    else:
        out = block + text
    return (b"\xef\xbb\xbf" if bom else b"") + out.encode(enc, "replace")


def _decode_record(data: bytes) -> tuple[str, str]:
    """Decode a record as UTF-8, else the Windows ANSI code page agents often write
    (PowerShell Set-Content), so an encoding never crashes the gate. Returns (text, encoding)."""
    try:
        return data.decode("utf-8"), "utf-8"
    except UnicodeDecodeError:
        try:
            return data.decode("cp1252"), "cp1252"
        except UnicodeDecodeError:
            return data.decode("latin-1"), "latin-1"


def _record_text(data: Optional[bytes]) -> Optional[str]:
    """A decision record's text with LF newlines; tolerant of non-UTF-8 encodings."""
    if data is None:
        return None
    if data.startswith(b"\xef\xbb\xbf"):
        data = data[3:]
    return _decode_record(data)[0].replace("\r\n", "\n").replace("\r", "\n")


def with_facts(data: bytes, block_lines: list[str]) -> bytes:
    """Replace (or append) the facts block; bytes outside the markers stay identical."""
    bom = data.startswith(b"\xef\xbb\xbf")
    text, enc = _decode_record(data[3:] if bom else data)
    nl = "\r\n" if "\r\n" in text else "\n"
    block = nl.join([BEGIN] + block_lines + [END]) + nl
    before, old, after = split_facts(text)
    if old is None:
        if before and not before.endswith("\n"):
            before += nl
        if before.strip():
            before += nl                          # one blank line before the block
        out = before + block
    else:
        out = before + block + after
    return (b"\xef\xbb\xbf" if bom else b"") + out.encode(enc, "replace")


