def render_stdout(rec: dict, action: list[str]) -> str:
    c = rec["counts"]
    head = (f"DECISION RECORD: {rec['verdict'].upper()} ({rec['mode']} mode) - "
            f"{rec['record_path'] or 'no record'}: {c[ERROR]} error(s), {c[WARN]} warning(s), "
            f"{c[INFO]} info  [{rec['compared']}]")
    out = [head]
    errs = [f for f in rec["findings"] if f["severity"] == ERROR]
    warns = [f for f in rec["findings"] if f["severity"] == WARN]
    if errs:
        out.append("ERRORS (must fix):")
        out += [f"  - {f['message']}" for f in errs]
        out.append("ACTION: " + "; ".join(action) + ".")
    if warns:
        out.append("WARNINGS (not blocking; fix the record if it is wrong):")
        out += [f"  - {f['message']}" for f in warns[:30]]
        if len(warns) > 30:
            out.append(f"  ... {len(warns) - 30} more in the record")
    cov = rec["coverage"]
    out.append(f"coverage: {cov['mentioned']}/{cov['changed_components']} changed component(s) "
               f"mentioned; out-of-scope explained {rec['out_of_scope']['explained']}/"
               f"{rec['out_of_scope']['total']}; removed symbols mentioned "
               f"{rec['removed_symbols']['mentioned']}/{rec['removed_symbols']['total']}")
    return "\n".join(out)


