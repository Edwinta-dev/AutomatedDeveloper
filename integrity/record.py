def claim_items(body: str) -> list[str]:
    """Top-level bullets (with their indented continuation lines) and paragraphs."""
    items: list[str] = []
    para = False
    for line in body.split("\n"):
        s = line.strip()
        if not s:
            para = False
            continue
        if s.startswith("|"):
            if re.fullmatch(r"\|[\s|:\-]*\|?", s):
                if items:
                    items.pop()                       # the header row before a separator
                continue
            items.append(s)
            para = False
        elif re.match(r"^(?:[-*+]|\d+[.)])\s", line):
            items.append(s)
            para = False
        elif line[:1] in (" ", "\t") and items:
            items[-1] += " " + s
        elif para and items:
            items[-1] += " " + s
        else:
            items.append(s)
            para = True
    out = []
    for x in items:
        t = re.sub(r"^(?:[-*+]|\d+[.)])\s+", "", x).strip()
        if t and not (WAIVER_RE.match(t.strip("*_ ")) and len(t.split()) <= 12):
            out.append(t)
    return out


def _bare_numbers(item: str) -> list[float]:
    bare = re.sub(r"`[^`]*`", " ", item)
    bare = re.sub(r"\[[^\]]*\]\([^)]*\)", " ", bare)
    return [float(x) for x in NUM_RE.findall(bare)]


class EvidenceCtx:
    def __init__(self, repo, trees, rows, rev, gates, test_gate_re):
        self.repo, self.trees, self.rows, self.rev = repo, trees, rows, rev
        self.changed_paths = {r["path"] for r in rows} | {r["old_path"] for r in rows
                                                          if r.get("old_path")}
        self.code_paths = [p for p in sorted(self.changed_paths)
                           if refs.hit_class(p) not in ("test", "doc")]
        self.test_gate = None if gates is None else next(
            (g for g in gates if re.search(test_gate_re, g)), "")
        self._tests: dict = {}

    def test_exists(self, name: str) -> bool:
        if name not in self._tests:
            self._tests[name] = _test_name_exists(self.repo, self.rev, name)
        return self._tests[name]

    def comp_check(self, item: str) -> Optional[str]:
        """None: the item names no code. '': every named component exists and changed.
        Otherwise the reason it could not be confirmed."""
        t = self.trees
        crefs = [(p, q) for p, q in comp_refs(item) if refs.hit_class(p) != "test"]
        prefs = [p for p in path_refs(item) if refs.hit_class(p) not in ("test", "doc")]
        if not crefs and not prefs:
            return None
        for p, q in crefs:
            st, ps = t.resolve(p, q)
            if st not in ("exact", "suffix"):
                return f"`{p}` not found"
            if not any(t.has_comp(x, q) for x in ps):
                return f"`{p}::{q}` not found"
            bq = base_qualname(q)
            if not any(r["path"] in ps and (r["component"] in PSEUDO or q in PSEUDO
                                             or base_qualname(r["component"]) == bq
                                             or base_qualname(r["component"]).startswith(bq + ".")
                                             or bq.startswith(base_qualname(r["component"]) + "."))
                       for r in self.rows):
                return f"`{p}::{q}` exists but did not change"
        for p in prefs:
            st, ps = t.resolve(p)
            if st not in ("exact", "suffix"):
                return f"`{p}` not found"
            if not any(x == c or c.startswith(x.rstrip("/") + "/") for x in ps
                       for c in self.changed_paths):
                return f"`{p}` did not change"
        return ""

    def test_check(self, item: str) -> Optional[tuple[str, str]]:
        """None: no test cited. Else (level, note)."""
        files = [p for p in path_refs(item) if refs.hit_class(p) == "test"]
        names = list(TEST_NAME_RE.findall(item))
        for p, q in comp_refs(item):
            if refs.hit_class(p) == "test":
                files.append(p)
                names.append(base_qualname(q).rsplit(".", 1)[-1])
        if not files and not names:
            return None
        for p in dict.fromkeys(files):
            if self.trees.resolve(p)[0] == "missing":
                return "claimed", f"cited test file `{p}` not found"
        for n in dict.fromkeys(names):
            if not self.test_exists(n):
                return "claimed", f"cited test `{n}` not found"
        if self.test_gate:
            return "tested", f"test gate passed: {self.test_gate}"
        return "claimed", ("cited test exists; no passed test gate in this run"
                           if self.test_gate is not None else
                           "cited test exists; gate results not available")

    def param_check(self, item: str) -> Optional[tuple[str, str]]:
        nums = _bare_numbers(item)
        if not nums:
            return None
        cands: list[tuple[str, list[str]]] = []
        for p, q in comp_refs(item):
            if re.fullmatch(r"[A-Za-z_]\w*", q):
                st, ps = self.trees.resolve(p, q)
                if st in ("exact", "suffix"):
                    cands.append((q, ps))
        for m in BACKTICK_RE.finditer(item):
            n = m.group(1).strip()
            if re.fullmatch(r"[A-Za-z_]\w*", n) and not any(c[0] == n for c in cands):
                cands.append((n, self.code_paths))
        found, bad = [], []
        for name, ps in cands:
            for x in ps:
                val, _ = const_value(refs._decode(self.trees.read(x, "new")), name)
                if val is None:
                    continue
                if any(abs(n * f - val) <= max(abs(val) * 0.15, 1e-9)
                       for n in nums for f in UNIT_FACTORS):
                    found.append(f"{name} = {_fmt(val)}")
                else:
                    bad.append(f"{name} = {_fmt(val)}")
                break
        if found and not bad:
            return "checked", "value matches the code: " + ", ".join(found[:3])
        if bad:
            return "claimed", "value differs from the code: " + ", ".join(bad[:3])
        return None


def classify_claim(section: str, item: str, ctx: EvidenceCtx) -> tuple[str, str]:
    if section not in EVIDENCE_SECTIONS:
        return "claimed", "this section is never confirmed by the tool"
    if section == "Key parameters":
        r = ctx.param_check(item)
        if r:
            return r
        tc = ctx.test_check(item)
        if tc and tc[0] == "tested":
            return tc
        return "claimed", "no cited constant with a matching value"
    if section in ("How it was verified", "Edge cases"):
        tc = ctx.test_check(item)
        if tc:
            return tc
        if section == "How it was verified":
            return "claimed", "no test named"
    cc = ctx.comp_check(item)
    if cc == "":
        return "checked", "named code exists and changed"
    return "claimed", cc or "names no code"


def evidence(parsed: "Parsed", ctx: EvidenceCtx) -> dict:
    secs: dict = {}
    items: list[dict] = []
    for h, body in parsed.sections:
        name = next((s for s in EVIDENCE_SECTIONS + CLAIMED_SECTIONS
                     if _norm_heading(h).startswith(_norm_heading(s))), None)
        if name is None:
            continue
        for it in claim_items(body):
            if name == "Edge cases" and re.search(r"\bnot\s+handled\b", it, re.I):
                continue
            level, note = classify_claim(name, it, ctx)
            c = secs.setdefault(name, {"checked": 0, "tested": 0, "claimed": 0})
            c[level] += 1
            items.append({"section": name, "level": level, "claim": it, "note": note})
    totals = {k: sum(c[k] for c in secs.values()) for k in ("checked", "tested", "claimed")}
    return {"sections": secs, "totals": totals, "items": items,
            "test_gate": ctx.test_gate}


def section_items(parsed: "Parsed", name: str) -> list[str]:
    sec = find_section(parsed, name)
    if sec is None or is_waiver(sec[1]):
        return []
    return claim_items(sec[1])


