@dataclass
class Parsed:
    title: str = ""
    status_raw: Optional[str] = None
    status: Optional[str] = None
    sections: list[tuple[str, str]] = field(default_factory=list)   # (heading, body)
    words: int = 0
    date: Optional[str] = None


def _norm_heading(h: str) -> str:
    h = re.sub(r"[*_`]", "", h).strip().lower()
    return re.sub(r"\s+", " ", h).rstrip(":").strip()


def parse_markdown(text: str) -> Parsed:
    p = Parsed()
    cur: Optional[list] = None
    fenced = False
    pre: list[str] = []
    for line in text.split("\n"):
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
        if not fenced and re.match(r"^##\s+\S", line) and not line.startswith("###"):
            cur = [line[2:].strip(), []]
            p.sections.append(cur)  # type: ignore[arg-type]
            continue
        if not fenced and re.match(r"^#\s+\S", line) and cur is None and not p.title:
            p.title = line[1:].strip()
            continue
        (cur[1] if cur is not None else pre).append(line)
    p.sections = [(h, "\n".join(b).strip()) for h, b in p.sections]
    for line in pre:
        m = re.search(r"\bstatus\s*\**\s*:\s*\**\s*([A-Za-z]+)(\s*\|)?", line, re.IGNORECASE)
        if m:
            p.status_raw = line.strip()
            v = m.group(1).lower()
            p.status = v if v in STATUSES and not m.group(2) else None
            break
    for line in pre:
        m = re.search(r"\bdate\s*\**\s*:\s*\**\s*(\d{4}-\d{2}-\d{2})", line, re.IGNORECASE)
        if m:
            p.date = m.group(1)
            break
    p.words = len(re.findall(r"[A-Za-z0-9][\w'’.:/-]*", text))
    return p


def find_section(p: Parsed, name: str) -> Optional[tuple[str, str]]:
    want = _norm_heading(name)
    for h, body in p.sections:
        if _norm_heading(h).startswith(want):
            return h, body
    return None


def is_waiver(body: str) -> bool:
    s = " ".join(re.sub(r"^\s*(?:[-*>]|\d+\.)\s*", "", ln) for ln in body.split("\n")).strip()
    if not s:
        return True
    return bool(WAIVER_RE.match(s)) and len(s.split()) <= 12


