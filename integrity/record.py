NUM_RE = re.compile(r"(?<![\w.#/\-])(\d+(?:\.\d+)?)(?![\w.]*\w)")
ASSIGN_RES = [
    r"^\s*#\s*define\s+{n}\s+([^\n]+?)\s*(?://[^\n]*|/\*[^\n]*)?$",
    r"^\s*(?:self\.)?{n}\s*(?::[^=\n]+)?=\s*([^\n]+?)\s*(?:#[^\n]*)?$",
    r"\b(?:const|constexpr|final|let|var)\b[^=;\n(]*?\b{n}\s*(?:\[\])?=\s*([^;\n]+);",
    r"^\s*(?:static\s+)?(?:const\s+)?[\w:<>]+\s+{n}\s*=\s*([^;\n]+);",
]
UNIT_FACTORS = (1, 1000, 0.001, 60, 1 / 60, 3600, 1 / 3600, 100, 0.01, 1024, 1 / 1024,
                86400, 1 / 86400, 1e6, 1e-6)


def _lookup_expr(src: str, name: str) -> Optional[str]:
    for pat in ASSIGN_RES:
        m = re.search(pat.format(n=re.escape(name)), src, re.M)
        if m:
            return m.group(1).strip().rstrip(",;").strip()
    return None


def _num_literal(tok: str) -> Optional[float]:
    t = tok.strip().replace("_", "").replace("'", "")
    t = re.sub(r"(?<=[\d.])(?:[uU]?[lL]{1,2}|[uU]|[fF])$", "", t)
    try:
        if re.fullmatch(r"0[xX][\da-fA-F]+|0[bB][01]+|0[oO][0-7]+|\d+", t):
            return float(int(t, 0) if not re.fullmatch(r"0\d+", t) else int(t))
        if re.fullmatch(r"-?\d+\.?\d*(?:[eE][-+]?\d+)?|-?\.\d+", t):
            return float(t)
    except ValueError:
        return None
    return None


def const_value(src: str, name: str, depth: int = 0) -> tuple[Optional[float], bool]:
    """-> (value, is_single_literal). Simple literals, or +-*/ of literals and other
    constants of the same file (up to 3 levels); anything else -> (None, False)."""
    import ast
    expr = _lookup_expr(src, name) if depth <= 3 else None
    if expr is None:
        return None, False
    expr = re.sub(r"\(\s*(?:u?int\d*_t|float|double|long|unsigned(?:\s+long)?)\s*\)", "", expr)
    v = _num_literal(expr.strip("() "))
    if v is not None:
        return v, True
    py = re.sub(r"(?<=[\d.])(?:[uU]?[lL]{1,2}|[uU]|[fF])\b", "", expr)
    py = re.sub(r"(?<=\d)_(?=\d)", "", py)
    try:
        tree = ast.parse(py.strip(), mode="eval")
    except SyntaxError:
        return None, False

    def ev(n):
        if isinstance(n, ast.Constant) and isinstance(n.value, (int, float)) \
                and not isinstance(n.value, bool):
            return float(n.value)
        if isinstance(n, ast.BinOp) and isinstance(n.op, (ast.Add, ast.Sub, ast.Mult, ast.Div)):
            a, b = ev(n.left), ev(n.right)
            if a is None or b is None or (isinstance(n.op, ast.Div) and b == 0):
                return None
            if isinstance(n.op, ast.Add):
                return a + b
            if isinstance(n.op, ast.Sub):
                return a - b
            if isinstance(n.op, ast.Mult):
                return a * b
            return a / b
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.USub):
            x = ev(n.operand)
            return -x if x is not None else None
        if isinstance(n, ast.Name) and n.id != name:
            return const_value(src, n.id, depth + 1)[0]
        return None
    return ev(tree.body), False


def _fmt(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else f"{v:g}"


def claim_units(text: str) -> list[str]:
    """Bullets / table rows whole; other lines split into sentences."""
    out = []
    for line in text.split("\n"):
        if re.match(r"^\s*(?:[-*]|\d+\.)\s", line) or line.lstrip().startswith("|"):
            out.append(line)
        else:
            out += [x for x in re.split(r"(?<=[.!?])\s+(?=[A-Z`(])", line) if x.strip()]
    return out


def numeric_claims(text: str, trees: "Trees") -> list[dict]:
    """Each cited constant next to a number, with its value in the new tree. A claim is a
    contradiction only when one single-literal constant is cited alone in a sentence with
    exactly one number that matches it under no common unit factor (1, 60, 1000, ...)."""
    out, seen = [], set()
    for unit in claim_units(text):
        crefs = [(p, q) for p, q in comp_refs(unit) if re.fullmatch(r"[A-Za-z_]\w*", q)]
        if not crefs:
            continue
        bare = re.sub(r"`[^`]*`", " ", unit)
        bare = re.sub(r"\[[^\]]*\]\([^)]*\)", " ", bare)
        nums = [float(x) for x in NUM_RE.findall(bare)]
        if not nums:
            continue
        for p, q in crefs:
            if (p, q, unit) in seen:
                continue
            seen.add((p, q, unit))
            st, ps = trees.resolve(p, q)
            if st not in ("exact", "suffix"):
                continue
            val, single = None, False
            for x in ps:
                val, single = const_value(refs._decode(trees.read(x, "new")), q)
                if val is not None:
                    break
            if val is None:
                continue
            item = {"ref": f"{p}::{q}", "name": q, "value": val, "numbers": nums,
                    "contradiction": False}
            if single and len(crefs) == 1 and len(nums) == 1 and nums[0] != 0:
                item["contradiction"] = not any(
                    abs(nums[0] * f - val) <= max(abs(val) * 0.15, 1e-9) for f in UNIT_FACTORS)
            out.append(item)
    return out


