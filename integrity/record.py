class Trees:
    def __init__(self, repo: Path, old_rev: str, new_rev: Optional[str]):
        self.repo, self.old_rev, self.new_rev = repo, old_rev, new_rev
        self._ex: dict = {}
        self._bytes: dict = {}

    def exists(self, path: str, side: str) -> bool:
        key = (path, side)
        if key not in self._ex:
            rev = self.old_rev if side == "old" else self.new_rev
            if rev is None:
                self._ex[key] = (self.repo / path).exists()
            elif rev == EMPTY_TREE:
                self._ex[key] = False
            else:
                self._ex[key] = git(self.repo, "cat-file", "-e", f"{rev}:{path.rstrip('/')}",
                                    check=False).returncode == 0
        return self._ex[key]

    def read(self, path: str, side: str) -> Optional[bytes]:
        key = (path, side)
        if key not in self._bytes:
            rev = self.old_rev if side == "old" else self.new_rev
            if rev is None:
                f = self.repo / path
                self._bytes[key] = f.read_bytes() if f.is_file() else None
            elif rev == EMPTY_TREE:
                self._bytes[key] = None
            else:
                p = git(self.repo, "show", f"{rev}:{path}", check=False)
                self._bytes[key] = p.stdout if p.returncode == 0 else None
        return self._bytes[key]

    def qualnames(self, path: str, side: str) -> Optional[set[str]]:
        data = self.read(path, side)
        if data is None:
            return None
        parsed = adapter_for(path).parse(data, path)
        if parsed.error:
            return None
        return {base_qualname(c.qualname) for c in parsed.components} | set(PSEUDO)

    def list_dir(self, d: str) -> list[str]:
        d = norm_path(d).rstrip("/")
        if self.new_rev is None:
            base = self.repo / d
            return sorted(f"{d}/{x.name}" for x in base.iterdir() if x.is_file()) \
                if base.is_dir() else []
        out = git_text(self.repo, "ls-tree", "--name-only", self.new_rev, "--", d + "/")
        return sorted(norm_path(x) for x in out.splitlines() if x.strip())

    # -- path resolution: records often name paths relative to a subproject
    #    (`koi/x.py` for `Backend/koi/x.py`) or as bare file names (`x.py`).
    def tracked(self) -> tuple[set, set]:
        """(files, dirs) present in the old or the new tree."""
        if not hasattr(self, "_tracked"):
            files: set = set()
            for rev in (self.old_rev, self.new_rev):
                if rev == EMPTY_TREE:
                    continue
                if rev is None:
                    out = git_text(self.repo, "ls-files", "-co", "--exclude-standard")
                else:
                    out = git_text(self.repo, "ls-tree", "-r", "--name-only", rev)
                files.update(norm_path(x) for x in out.splitlines() if x.strip())
            dirs = {f.rsplit("/", i)[0] for f in files for i in range(1, f.count("/") + 1)}
            self._tracked = (files, dirs)
            self._res: dict = {}
        return self._tracked

    def resolve(self, ref: str, comp: Optional[str] = None) -> tuple[str, list[str]]:
        """-> (status, repo paths). status: exact | suffix | ambiguous | missing.
        exact: the path exists from the repo root; suffix: exactly one tracked path ends with
        it (segment aligned), or several do and some hold `comp` (those are returned);
        ambiguous: several match and `comp` does not disambiguate."""
        ref = norm_path(ref)
        files, dirs = self.tracked()
        key = (ref, comp)
        if key in self._res:
            return self._res[key]
        r = ref.rstrip("/")
        if r in files or r in dirs or self.exists(r, "old") or self.exists(r, "new"):
            res = ("exact", [r])
        else:
            pool = dirs if ref.endswith("/") else files | dirs
            m = sorted(x for x in pool if x.endswith("/" + r))
            live = [x for x in m if not refs._excluded(x, refs.DEFAULT_EXCLUDE)]
            if len(m) > 1 and len(live) == 1:
                m = live                      # an archived copy does not make it ambiguous
            if not m:
                res = ("missing", [])
            elif len(m) == 1:
                res = ("suffix", m)
            else:
                hold = [x for x in m if comp is not None and self.has_comp(x, comp)]
                res = ("suffix", hold) if hold else ("ambiguous", m)
        self._res[key] = res
        return res

    def has_comp(self, path: str, q: str) -> bool:
        if adapter_for(path).name == "file":
            return True
        names = (self.qualnames(path, "old") or set()) | (self.qualnames(path, "new") or set())
        return base_qualname(q) in names

    def aliases(self, path: str) -> list[str]:
        """`path` and every segment-aligned suffix of it that resolves to it alone."""
        parts = path.split("/")
        out = [path]
        for i in range(1, len(parts)):
            sfx = "/".join(parts[i:])
            st, ps = self.resolve(sfx)
            if st == "suffix" and ps == [path]:
                out.append(sfx)
            elif st == "ambiguous" and path in ps and \
                    [x for x in ps if x in getattr(self, "changed", ())] == [path]:
                out.append(sfx)          # only one of the same-named files changed
        return out


