ELLIPSIS_RE = re.compile(r"(?<![\w/.])(?:\.\.\.|…)::([A-Za-z_][\w.]*)")


def expand_ellipsis(text: str, trees: "Trees", paths) -> str:
    """`...::name` / `…::name` -> `path::name` when exactly one changed file defines `name`."""
    paths = [p for p in paths if adapter_for(p).name != "file"]
    cache: dict = {}

    def names(p):
        if p not in cache:
            cache[p] = (trees.qualnames(p, "new") or set()) | (trees.qualnames(p, "old") or set())
        return cache[p]

    def repl(m):
        name = m.group(1).rstrip(".")
        hits = [p for p in paths if base_qualname(name) in names(p)]
        return f"{hits[0]}::{name}" if len(hits) == 1 else m.group(0)
    return ELLIPSIS_RE.sub(repl, text)


def git_ignored(repo: Path, path: str) -> bool:
    try:
        return git(repo, "check-ignore", "-q", "--", path.rstrip("/"),
                   check=False).returncode == 0
    except Exception:            # noqa: BLE001 - an odd path is simply "not ignored"
        return False


def same_file_helper(path: str, q: str, trees: "Trees", repo: Path, rev: Optional[str],
                     cache: dict) -> bool:
    """A helper that lives beside a scoped / described component: private, or a top-level
    name used again in its own file and referenced by no other non-test, non-doc file.
    Conservative: module-level code, imports and whole files never count."""
    if q in PSEUDO or q == FILE:
        return False
    key = (path, q)
    if key in cache:
        return cache[key]
    ok = False
    if is_private(path, q, trees):
        ok = True
    else:
        top = base_qualname(q).split(".")[0]
        src = refs._decode(trees.read(path, "new"))
        if src and len(re.findall(r"(?<![\w$])" + re.escape(top) + r"(?![\w$])", src)) >= 2:
            args = ["grep", "-l", "-w", "-F", "-I", "-e", top]
            args += ["--untracked"] if rev is None else [rev]
            p = git(repo, *args, check=False)
            prefix = f"{rev}:" if rev else ""
            others = []
            for ln in p.stdout.decode("utf-8", "replace").splitlines():
                f = norm_path(ln[len(prefix):] if prefix and ln.startswith(prefix) else ln)
                if f != path and refs.hit_class(f) not in ("test", "doc")                         and not refs._excluded(f, refs.DEFAULT_EXCLUDE):
                    others.append(f)
            ok = not others
    cache[key] = ok
    return ok


