def load_config(path: Optional[Path]) -> dict:
    """The "record" section of a project config JSON; missing file/section -> defaults."""
    cfg = {k: (list(v) if isinstance(v, list) else v) for k, v in DEFAULT_CONFIG.items()}
    if path is None or not Path(path).is_file():
        return cfg
    data = json.loads(Path(path).read_text(encoding="utf-8-sig"))
    if not isinstance(data, dict):
        raise ValueError("config root must be a JSON object")
    sec = data.get("record", {})
    if not isinstance(sec, dict):
        raise ValueError('"record" section must be an object')
    for k, v in sec.items():
        if k.startswith("//") or k.startswith("_"):
            continue
        if k not in DEFAULT_CONFIG:
            raise ValueError(f"unknown record config key {k!r}")
        cfg[k] = v
    if cfg["mode"] not in ("report", "enforce"):
        raise ValueError(f"record.mode must be 'report' or 'enforce', not {cfg['mode']!r}")
    if not isinstance(cfg["dir"], str) or not cfg["dir"].strip():
        raise ValueError("record.dir must be a non-empty string")
    rs = cfg["required_sections"]
    if not isinstance(rs, list) or not all(isinstance(x, str) and x.strip() for x in rs):
        raise ValueError("record.required_sections must be a list of strings")
    for k in ("min_words", "max_words"):
        if not isinstance(cfg[k], int) or isinstance(cfg[k], bool) or cfg[k] < 0:
            raise ValueError(f"record.{k} must be a non-negative integer")
    return cfg


