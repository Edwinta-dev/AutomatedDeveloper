"""
record.py — decision record check + verified-facts block. Standard library only.

Each issue leaves a decision record `<dir>/<NNNN>-<slug>.md` (see docs/DECISION_RECORDS.md).
The agent writes the rationale; this module

  1. locates the record and checks it was written/updated by this change,
  2. checks it for consistency with the change (deterministic: required sections, Status,
     length, references to code that does not exist, changed components the record never
     mentions, unexplained out-of-scope changes, unmentioned removed symbols, verification
     claims naming tests that do not exist),
  3. appends (or replaces) a tool-generated "Verified facts" block at the end of the record
     (working-tree mode only; the runner then commits it with the change).

    check_record(repo, cfg=..., issue=N, ...) -> (exit code, json record, stdout text)

Reuses scope.py (change collection + component comparison), components.py (adapters) and
refs.py (symbol extraction, dangling verdicts). Knows nothing about the runner (engine/).
"""
