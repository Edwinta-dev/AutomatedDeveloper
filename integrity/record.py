URLISH_RE = re.compile(r"https?:|://|\?|<\w+:|(?:^|/)v\d+/|^(?:api|rpc|rest|auth|storage)/",
                       re.IGNORECASE)
DIR_TOKEN_RE = re.compile(r"(?<![\w/.\-])([\w.\-]+(?:/[\w.\-]+)*/)(?![\w.\-])")


def url_like(ref: str, trees: "Trees") -> bool:
    """A route, URL or slash-separated identifier (`/v1/x`, `rpc/http_get`, `GY33_R/G/B`),
    not a repo path: URL markers, or no file extension and a first segment that is no
    tracked directory."""
    if URLISH_RE.search(ref):
        return True
    r = ref.rstrip("/")
    if Path(r).suffix.lower() in KNOWN_EXTS:
        return False
    first = r.split("/")[0]
    _, dirs = trees.tracked()
    names = {d.rsplit("/", 1)[-1] for d in dirs}
    return first not in names


def mentioned_dirs(text: str, trees: "Trees") -> list[str]:
    """Repo directories the record names (a path ending in `/`, or a backticked path that
    is a directory in the old or new tree); files under them count as mentioned."""
    _, dirs = trees.tracked()
    cands = [m.group(1) for m in DIR_TOKEN_RE.finditer(text)]
    cands += [p for p in path_refs(text) if not Path(p.rstrip("/")).suffix]
    out = []
    for c in dict.fromkeys(cands):
        c = norm_path(c).rstrip("/")
        if not c or "/" not in c and c not in {d.rsplit("/", 1)[-1] for d in dirs}:
            continue
        st, ps = trees.resolve(c + "/")
        if st in ("exact", "suffix"):
            out += [x.rstrip("/") for x in ps if x.rstrip("/") in dirs]
    return list(dict.fromkeys(out))


def under_dirs(path: Optional[str], ds: list[str]) -> bool:
    return bool(path) and any(path.startswith(d + "/") for d in ds)


JS_EXTS = (".js", ".mjs", ".cjs", ".jsx", ".ts", ".tsx")
C_EXTS = (".c", ".h", ".cc", ".cpp", ".hpp", ".ino")


def is_private(path: str, q: str, trees: "Trees") -> bool:
    """A private helper: Python/Dart `_name` (not dunder), a C/C++ `static` function, or
    a JS/TS top-level name that is never exported."""
    if q in PSEUDO or q == FILE:
        return False
    bq = base_qualname(q)
    parts = bq.split(".")
    if any(x.startswith("_") and not (x.startswith("__") and x.endswith("__")) for x in parts):
        return True
    ext = Path(path).suffix.lower()
    if ext not in C_EXTS + JS_EXTS:
        return False
    src = refs._decode(trees.read(path, "new") or trees.read(path, "old"))
    top = parts[0]
    if ext in C_EXTS:
        return bool(re.search(r"^\s*static\b[^;{}()=]*\b" + re.escape(top) + r"\s*\(", src,
                              re.M))
    if re.search(r"module\.exports|\bexports\.", src):
        return not any(re.search(r"\b" + re.escape(top) + r"\b", g)
                       for g in re.findall(r"(?:module\.)?exports[^;]*", src))
    exported = re.search(r"\bexport\s+(?:default\s+)?(?:async\s+)?(?:function\*?|class|const|let|"
                         r"var|interface|type|enum)\s+" + re.escape(top) + r"\b", src) or \
        any(re.search(r"\b" + re.escape(top) + r"\b", g)
            for g in re.findall(r"\bexport\s*\{([^}]*)\}", src))
    return not exported


def disambiguate(ps: list[str], ref: str, text: str) -> list[str]:
    """Of several files a suffix matches, the one whose leading directory the record names
    elsewhere (`MobileUI/mobile_app/...` disambiguates `lib/utils/x.dart`)."""
    r = ref.rstrip("/")
    hits = [x for x in ps if (pre := x[: -len(r)].rstrip("/")) and pre in text]
    return hits if len(hits) == 1 else []


