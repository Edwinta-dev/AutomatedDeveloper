def removed_symbols(cs, trees: Trees) -> list[dict]:
    """Symbols the old side of a changed file defines that no changed file defines any more."""
    new_defs: dict = {}
    for c in cs.changes:
        if c.change == "removed":
            continue
        fam = refs.family(c.path)
        txt = refs._decode(trees.read(c.path, "new"))
        new_defs.setdefault(fam, set()).update(refs.defined_names(c.path, txt)[1])
    out, seen = [], set()
    for c in cs.changes:
        if c.change == "added":
            continue
        src = c.old_path or c.path
        if refs.hit_class(src) in ("test", "doc"):
            continue
        old_syms = refs.extract(src, refs._decode(trees.read(src, "old")))
        if not old_syms:
            continue
        new_syms = set() if c.change == "removed" else \
            refs.extract(c.path, refs._decode(trees.read(c.path, "new")))
        new_names = {s.name for s in new_syms}
        gone_classes = {s.name for s in old_syms if s.kind == "class"} - new_names
        for s in sorted(old_syms, key=lambda s: s.display):
            if s.kind == "variable" or s.name in new_names:
                continue
            if s.kind == "method" and s.display.split(".")[0] in gone_classes:
                continue
            if s.name in new_defs.get(refs.family(src), set()):
                continue                                   # moved to another changed file
            if (src, s.display) in seen:
                continue
            seen.add((src, s.display))
            out.append({"symbol": s.display, "name": s.name, "kind": s.kind, "path": src})
    return out


